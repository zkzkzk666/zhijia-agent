def build_system_prompt(role: str, custom: str | None = None) -> str:
    role_prompt = ROLES.get(role, ROLES["general"]).get("prompt", "")
    if custom and custom.strip():
        return custom.strip()
    return "\n".join(part for part in (BASE_PROMPT, role_prompt) if part)


